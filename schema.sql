-- Validating a sale credits dirty cash exactly once, in the same transaction as the status change.
create or replace function public.credit_validated_sale()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.status='Validée' and new.status is distinct from 'Validée' then
    raise exception 'Une vente validée ne peut pas être annulée.';
  end if;
  if new.status='Validée' and old.status is distinct from 'Validée' then
    insert into public.cash_ledger(account,amount,note,created_by)
    values('sale',new.amount,'Vente REECEL validée · '||new.quantity||' × '||new.name,new.reviewed_by);
  end if;
  return new;
end; $$;
drop trigger if exists sales_credit_dirty_cash on public.sales;
create trigger sales_credit_dirty_cash after update of status on public.sales for each row execute function public.credit_validated_sale();

create or replace function public.approve_application(application_id bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare a public.applications%rowtype; m public.members%rowtype;
begin
  if not public.has_family_rank(array['👑・EL PATRÓN','🥇・MANO DERECHA','🥈・MANO DE IZQUIERDA','✉️・JEFE RECRUTEMENT']) then raise exception 'Décision réservée au recrutement et aux modérateurs.'; end if;
  select * into a from public.applications where id=application_id for update;
  if not found or a.status <> 'En attente' then raise exception 'Candidature introuvable ou déjà traitée.'; end if;
  update public.applications set status='Acceptée' where id=a.id returning * into a;
  insert into public.members(name,email,rank) values(a.name,a.email,'👤・RECRUE') returning * into m;
  return jsonb_build_object('application',to_jsonb(a),'member',to_jsonb(m));
end; $$;
grant execute on function public.approve_application(bigint) to authenticated;

-- Managers may add catalog entries. A missing matching stock item is created at zero units.
create or replace function public.create_reecel_product(product_name text, unit_price numeric, category text default 'Divers')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_item public.inventory_items%rowtype; v_product public.reecel_products%rowtype;
begin
  if not public.is_active_member() or not public.has_family_rank(array['👑・EL PATRÓN','🥇・MANO DERECHA','🥈・MANO DE IZQUIERDA','📦・JEFE REECEL','🤝・ASSISTANT REECEL']) then
    raise exception 'Création du catalogue réservée au REECEL et au haut commandement.';
  end if;
  if length(trim(product_name))=0 or unit_price is null or unit_price<=0 then raise exception 'Nom ou prix invalide.'; end if;
  select * into v_item from public.inventory_items where lower(name)=lower(trim(product_name)) for update;
  if not found then
    insert into public.inventory_items(name,category,quantity,icon,created_by)
    values(trim(product_name),coalesce(nullif(trim(category),''),'Divers'),0,
      case category when 'Arme' then '🔫' when 'Protection' then '🦺' when 'Accessoire' then '🔩' else '📦' end,(select auth.uid()))
    returning * into v_item;
  end if;
  insert into public.reecel_products(inventory_item_id,name,unit_price,created_by)
  values(v_item.id,trim(product_name),unit_price,(select auth.uid())) returning * into v_product;
  return jsonb_build_object('id',v_product.id,'inventory_item_id',v_item.id,'name',v_product.name,'unit_price',v_product.unit_price,'active',v_product.active,'created_at',v_product.created_at,
    'item',jsonb_build_object('id',v_item.id,'name',v_item.name,'category',v_item.category,'quantity',v_item.quantity,'icon',v_item.icon));
end; $$;
grant execute on function public.create_reecel_product(text,numeric,text) to authenticated;

-- Checkout applies cash, stock and its receipt atomically. Vente adds dirty cash and consumes stock;
-- Rachat spends dirty cash and adds stock. All totals come from the saved catalog prices.
create or replace function public.checkout_reecel_cart(transaction_kind text, cart_items jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_kind text := transaction_kind;
  v_line record;
  v_product public.reecel_products%rowtype;
  v_stock integer;
  v_total numeric(14,2) := 0;
  v_cash numeric(14,2) := 0;
  v_lines jsonb := '[]'::jsonb;
  v_inventory jsonb;
  v_tx public.reecel_transactions%rowtype;
  v_buyer text;
begin
  if not public.is_active_member() then raise exception 'Compte familial actif requis.'; end if;
  if v_kind not in ('Rachat','Vente') then raise exception 'Type de transaction invalide.'; end if;
  if cart_items is null or jsonb_typeof(cart_items) is distinct from 'array' then raise exception 'Le panier est invalide.'; end if;
  if jsonb_array_length(cart_items)=0 then raise exception 'Le panier est vide.'; end if;
  for v_line in
    select (e.value->>'product_id')::bigint as product_id, sum((e.value->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(cart_items) as e(value)
    group by (e.value->>'product_id')::bigint order by (e.value->>'product_id')::bigint
  loop
    if v_line.quantity<=0 then raise exception 'Quantité invalide.'; end if;
    select p.* into v_product from public.reecel_products p where p.id=v_line.product_id and p.active for update;
    if not found then raise exception 'Un article du panier n’est plus disponible.'; end if;
    select i.quantity into v_stock from public.inventory_items i where i.id=v_product.inventory_item_id for update;
    if not found then raise exception 'L’article associé est introuvable dans l’inventaire.'; end if;
    if v_kind='Vente' and v_stock<v_line.quantity then raise exception 'Stock insuffisant pour % (disponible : %).',v_product.name,v_stock; end if;
    v_total:=v_total+(v_product.unit_price*v_line.quantity);
    v_lines:=v_lines||jsonb_build_array(jsonb_build_object('product_id',v_product.id,'inventory_item_id',v_product.inventory_item_id,'name',v_product.name,'quantity',v_line.quantity,'unit_price',v_product.unit_price,'subtotal',v_product.unit_price*v_line.quantity));
  end loop;
  if v_kind='Rachat' then
    lock table public.cash_ledger in exclusive mode;
    select coalesce(sum(amount),0) into v_cash from public.cash_ledger where account='sale';
    if v_cash<v_total then raise exception 'Fonds insuffisants : la caisse sale contient %.',v_cash; end if;
  end if;
  for v_line in select (e.value->>'product_id')::bigint as product_id, sum((e.value->>'quantity')::integer)::integer as quantity from jsonb_array_elements(cart_items) as e(value) group by 1 order by 1 loop
    update public.inventory_items i set quantity=i.quantity+case when v_kind='Rachat' then v_line.quantity else -v_line.quantity end
      from public.reecel_products p where p.id=v_line.product_id and p.inventory_item_id=i.id;
  end loop;
  select coalesce(p.display_name,'Membre') into v_buyer from public.profiles p where p.id=(select auth.uid());
  insert into public.cash_ledger(account,amount,note,created_by)
  values('sale',case when v_kind='Vente' then v_total else -v_total end,'REECEL · '||v_kind||' · '||jsonb_array_length(v_lines)||' référence(s)',(select auth.uid()));
  insert into public.reecel_transactions(kind,total,items,buyer_id,buyer_name)
  values(v_kind,v_total,v_lines,(select auth.uid()),coalesce(v_buyer,'Membre')) returning * into v_tx;
  select coalesce(jsonb_agg(jsonb_build_object('id',i.id,'name',i.name,'category',i.category,'quantity',i.quantity,'icon',i.icon)),'[]'::jsonb)
    into v_inventory from public.inventory_items i join public.reecel_products p on p.inventory_item_id=i.id
    where p.id in (select (e.value->>'product_id')::bigint from jsonb_array_elements(cart_items) as e(value));
  return jsonb_build_object('transaction',to_jsonb(v_tx),'inventory',v_inventory);
end; $$;
grant execute on function public.checkout_reecel_cart(text,jsonb) to authenticated;

