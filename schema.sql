create or replace function public.create_profile_for_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_name text;
begin
  v_name := coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''),nullif(split_part(new.email,'@',1),''),'Nouveau membre');
  insert into public.profiles(id,display_name,rank) values(new.id,v_name,'👤・RECRUE') on conflict(id) do nothing;
  -- An accepted application with a matching email is linked to this login; otherwise create a roster entry.
  update public.members set user_id=new.id, name=coalesce(nullif(name,''),v_name), email=new.email, rank='👤・RECRUE'
    where id=(select m.id from public.members m where m.user_id is null and lower(m.email)=lower(new.email) order by m.created_at limit 1);
  if not exists(select 1 from public.members where user_id=new.id) then
    insert into public.members(name,email,user_id,rank) values(v_name,new.email,new.id,'👤・RECRUE');
  end if;
  return new;
end; $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute function public.create_profile_for_user();
insert into public.profiles(id,display_name,rank)
select u.id,coalesce(nullif(u.raw_user_meta_data ->> 'display_name',''),nullif(split_part(u.email,'@',1),''),'Nouveau membre'),'👤・RECRUE' from auth.users u on conflict(id) do nothing;
update public.members m set user_id=u.id, email=u.email
from auth.users u
where m.id=(select m2.id from public.members m2 where m2.user_id is null and lower(m2.email)=lower(u.email) order by m2.created_at limit 1)
  and not exists(select 1 from public.members linked where linked.user_id=u.id);
insert into public.members(name,email,user_id,rank)
select p.display_name,u.email,p.id,p.rank from public.profiles p join auth.users u on u.id=p.id
where not exists(select 1 from public.members m where m.user_id=p.id);

create or replace function public.has_family_rank(allowed_ranks text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.rank=any(allowed_ranks));
$$;
create or replace function public.is_active_member()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active);
$$;
create or replace function public.protect_profile_changes()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if (new.rank is distinct from old.rank or new.active is distinct from old.active)
     and (select auth.uid()) is not null
     and not public.has_family_rank(array['👑・EL PATRÓN','🥇・MANO DERECHA','🥈・MANO DE IZQUIERDA']) then
    raise exception 'Modification réservée aux trois modérateurs.';
  end if;
  return new;
end; $$;
drop trigger if exists profiles_rank_guard on public.profiles;
create trigger profiles_rank_guard before update on public.profiles for each row execute function public.protect_profile_changes();
create or replace function public.sync_profile_to_member()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.members set name=new.display_name, rank=new.rank where user_id=new.id;
  return new;
end; $$;
